#!/usr/bin/env node
// Build a scene timeline from the narration timings.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const filmArg = process.argv[2] ?? "deepinfer-open-source";
const film = join(root, "cuts", filmArg);
const timings = JSON.parse(readFileSync(join(film, "output", "audio", "vo", "timings.json"), "utf8"));

const lead = { hook: 0.45, name: 0.28, brain: 0.3, war: 0.3, open: 0.32, recipe: 0.28, inside: 0.32, cost: 0.3, control: 0.3, chips: 0.28, limits: 0.32, close: 0.45 };
const tail = { hook: 0.55, name: 0.4, brain: 0.45, war: 0.5, open: 0.5, recipe: 0.4, inside: 0.5, cost: 0.5, control: 0.45, chips: 0.4, limits: 0.55, close: 0.9 };
const intro = 1.0;
const outro = 3.4;

let cursor = intro;
const scenes = [];
for (const t of timings) {
  const start = +cursor.toFixed(3);
  const voStart = +(start + (lead[t.id] ?? 0.3)).toFixed(3);
  const voEnd = +(voStart + t.duration).toFixed(3);
  const end = +(voEnd + (tail[t.id] ?? 0.4)).toFixed(3);
  scenes.push({ id: t.id, text: t.text, words: t.words, start, voStart, voEnd, end, duration: +(end - start).toFixed(3) });
  cursor = end;
}
scenes.push({
  id: "outro", text: "", words: [],
  start: +cursor.toFixed(3), voStart: +cursor.toFixed(3), voEnd: +cursor.toFixed(3),
  end: +(cursor + outro).toFixed(3), duration: outro,
});
const total = +(cursor + outro).toFixed(3);
const timeline = { fps: 30, width: 1080, height: 1920, intro, total, outro, scenes };

writeFileSync(join(film, "output", "timeline.json"), JSON.stringify(timeline, null, 2) + "\n");
writeFileSync(
  join(film, "src", "generated", "timeline.js"),
  "// Generated by tools/timeline.mjs. Do not edit.\nexport const TIMELINE = " + JSON.stringify(timeline, null, 2) + ";\n"
);
console.log(scenes.map((s) => `${s.id.padEnd(8)} ${s.start.toFixed(2)} → ${s.end.toFixed(2)}  (${s.duration.toFixed(2)}s)`).join("\n"));
console.log(`TOTAL ${total}s`);
