type I18nContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  toggleLocale: () => void
  t: (key: string, values?: Record<string, string | number>) => string
  worldText: (world: WorldTextSource, key: keyof WorldTranslation) => string
  sourceText: (source: WorldSource) => string
  categoryText: (category: Category, key: 'title' | 'description') => string
  pathText: (path: Path, key: 'title' | 'description') => string
}

export function formatMessage(
  locale: Locale,
  key: string,
  values: Record<string, string | number> = {},
): string {
  let result = messages[locale][key] ?? messages.en[key] ?? key
  Object.entries(values).forEach(([name, value]) => {
    result = result.replaceAll(`{${name}}`, String(value))
  })
  return result
}

const I18nContext = createContext<I18nContextValue | null>(null)
const storageKey = localeCookieName

export function I18nProvider({ children, initialLocale = 'en' }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale)
  const [ready, setReady] = useState(false)

  useLayoutEffect(() => {
    const explicit = typeof window === 'undefined' ? undefined : readLocaleSearch(window.location.search)
    const stored = safeLocalStorage.get(storageKey)
    const next = explicit ?? (stored === 'zh' || stored === 'en' ? stored : initialLocale)
    document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en'
    setLocaleState(next)
    setReady(true)
  }, [initialLocale])

  useLayoutEffect(() => {
    if (!ready) return
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en'
    safeLocalStorage.set(storageKey, locale)
    const secure = window.location.protocol === 'https:' ? '; Secure' : ''
    document.cookie = `${storageKey}=${locale}; Path=/; Max-Age=31536000; SameSite=Lax${secure}`
  }, [locale, ready])

  const setLocale = useCallback((next: Locale) => setLocaleState(next), [])
  const toggleLocale = useCallback(() => setLocaleState((current) => current === 'en' ? 'zh' : 'en'), [])
  const t = useCallback((key: string, values: Record<string, string | number> = {}) => (
    formatMessage(locale, key, values)
  ), [locale])
  const worldText = useCallback((world: WorldTextSource, key: keyof WorldTranslation) => {
    if (key === 'evidence') {
      return locale === 'zh'
        ? ({live: '实时', verified: '已验证', compiled: '资料编译', modeled: '模型'} as const)[world.evidence]
        : ({live: 'Live', verified: 'Verified', compiled: 'Compiled', modeled: 'Modeled'} as const)[world.evidence]
    }
    return locale === 'zh'
      ? String(world[key] ?? '')
      : String(world.translations.en[key] ?? '')
  }, [locale])

  const sourceText = useCallback((source: WorldSource) => locale === 'zh' ? source.label : source.labelEn, [locale])
  const categoryText = useCallback((category: Category, key: 'title' | 'description') => (
    locale === 'zh' ? category[key] : category[key === 'title' ? 'titleEn' : 'descriptionEn']
  ), [locale])
  const pathText = useCallback((path: Path, key: 'title' | 'description') => (
    locale === 'zh' ? path[key] : path[key === 'title' ? 'titleEn' : 'descriptionEn']
  ), [locale])

  const value = useMemo(
    () => ({ locale, setLocale, toggleLocale, t, worldText, sourceText, categoryText, pathText }),
    [categoryText, locale, pathText, setLocale, sourceText, t, toggleLocale, worldText],
  )
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used within I18nProvider')
  return context
}

export function useOptionalI18n(): I18nContextValue | null {
  return useContext(I18nContext)
}
