/** Tables are stored at 5 nm; we pack every 2nd sample for 10 nm GPU steps. */
const TABLE_STRIDE = 2

/** Photometric normalization k = 1 / Σ(E·ȳ)·Δλ */
export function computeKNorm(): number {
  let sumEy = 0
  for (let i = 0; i < SPECTRAL_SAMPLES; i += 1) {
    const j = Math.min(i * TABLE_STRIDE, CIE_Y.length - 1)
    sumEy += D65[j]! * CIE_Y[j]!
  }
  return 1 / (sumEy * STEP_NM)
}

/**
 * Pack CMF × D65 into an RGBA float texture:
 * R = x̄, G = ȳ, B = z̄, A = E_D65
 */
export function createCmfTexture(): { texture: THREE.DataTexture; kNorm: number } {
  const n = SPECTRAL_SAMPLES
  const data = new Float32Array(n * 4)
  for (let i = 0; i < n; i += 1) {
    const j = Math.min(i * TABLE_STRIDE, CIE_X.length - 1)
    data[4 * i + 0] = CIE_X[j]!
    data[4 * i + 1] = CIE_Y[j]!
    data[4 * i + 2] = CIE_Z[j]!
    data[4 * i + 3] = D65[j]!
  }

  // Float CMF table (41×1 RGBA @ 10 nm). Nearest keeps each λ bin exact.
  const texture = new THREE.DataTexture(data, n, 1, THREE.RGBAFormat, THREE.FloatType)
  texture.needsUpdate = true
  texture.magFilter = THREE.NearestFilter
  texture.minFilter = THREE.NearestFilter
  texture.generateMipmaps = false
  texture.wrapS = THREE.ClampToEdgeWrapping
  texture.wrapT = THREE.ClampToEdgeWrapping
  texture.colorSpace = THREE.NoColorSpace

  return { texture, kNorm: computeKNorm() }
}
