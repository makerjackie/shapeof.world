import type { Cell } from './yield-model';

/**
 * The cow outline from CowMap, sampled on a 15.1-unit grid (x from 93.775, y
 * from 120). One column per string, top to bottom; '1' is inside the cow.
 * The spacing was chosen so the cow holds exactly 600 blocks: one block, one kilogram.
 */
export const CELL_SIZE = 15.1;
const X0 = 90 + 0.25 * CELL_SIZE;
const Y0 = 120;
const columns = [
	'00000000001', '00000001111', '00000111111', '00001111111', '00011111111', '00111111111', '00011111111', '000111111111',
	'0011111111111', '00111111111111', '011111111111111', '001111111111111', '0011111111111111', '011111111111111111',
	'0111111111111111111111', '0111111111111111111111', '00111111111111111111', '0011111111111111', '0011111111111111',
	'0011111111111111', '0011111111111111', '0011111111111111', '0011111111111111', '00111111111111111', '00111111111111111',
	'00111111111111111', '00111111111111111', '00111111111111111', '00111111111111111', '00111111111111111', '00111111111111111',
	'00111111111111111', '00111111111111111', '00111111111111111', '00111111111111111', '0011111111111111', '0111111111111111',
	'011111111111111', '011111111111111', '01111111111111111', '011111111111111111111', '0111111111111111111111',
	'0011111111111111000001', '0001111111111', '000001111',
];

export const cowCells: ReadonlyArray<Cell> = columns.flatMap((column, i) =>
	[...column].flatMap((bit, j) => (bit === '1' ? [{ x: X0 + i * CELL_SIZE, y: Y0 + j * CELL_SIZE }] : [])),
);
