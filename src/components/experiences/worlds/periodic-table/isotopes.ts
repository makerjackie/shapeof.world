const byAtomicNumber = new Map<number, readonly Isotope[]>(
  Array.from({ length: 118 }, (_, index) => {
    const atomicNumber = index + 1
    const isotopes = rows
      .filter(([z]) => z === atomicNumber)
      .map(([, mass, abundance]) => ({ mass, abundance }))
    return [atomicNumber, isotopes] as const
  }),
)

/** Return the NIST-listed isotopes for an atomic number (Z). */
export function isotopesFor(atomicNumber: number): Isotope[] {
  const isotopes = byAtomicNumber.get(atomicNumber)
  return isotopes ? isotopes.map((isotope) => ({ ...isotope })) : []
}
