const TOKEN = /[A-Za-z][A-Za-z'/-]*/g

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
}

function replacePhrases(value: string): string {
  let next = value
  for (const [english, chinese] of Object.entries(PHRASES)) {
    next = next.replace(new RegExp(escapeRegExp(english), "gi"), ` ${chinese} `)
  }
  return next.replace(/\s+/g, ' ').trim()
}

function translateSegment(value: string): string {
  const prepared = replacePhrases(value)
  const parts = prepared.split(/\s+/).filter(Boolean)
  return parts.map((part) => {
    const lower = part.toLowerCase()
    if (WORDS[lower] !== undefined) return WORDS[lower]
    const inner = lower.match(TOKEN)
    if (inner && inner.length === 1 && WORDS[inner[0]] !== undefined) return WORDS[inner[0]]
    return part
  }).join('')
}

export function translateAnatomyName(english: string): string {
  const trimmed = english.trim()
  if (!trimmed) return trimmed
  const direct = PHRASES[trimmed.toLowerCase()]
  if (direct) return direct
  const withTo = trimmed.split(/\s+to\s+/i)
  if (withTo.length > 1) {
    return withTo.map(translateAnatomyName).join('至')
  }
  const withWith = trimmed.split(/\s+with\s+/i)
  if (withWith.length > 1) {
    return withWith.map(translateAnatomyName).join('与')
  }
  const ofParts = trimmed.split(/\s+of\s+/i)
  if (ofParts.length > 1) {
    return ofParts.map(translateSegment).reverse().join('的')
  }
  return translateSegment(trimmed)
}

export function anatomySearchHaystack(english: string): string {
  return `${english} ${translateAnatomyName(english)}`.toLowerCase()
}
