/**
 * Bake public-domain portraits into an aspect-preserving luminance grid.
 * Usage: node bake-portraits.mjs <source-directory> <output.ts>
 * Wikimedia Commons source records below identify the exact public-domain works.
 */
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const [srcDir, outPath] = process.argv.slice(2)
if (!srcDir || !outPath) {
  console.error('usage: node bake-portraits.mjs <source-directory> <output.ts>')
  process.exit(1)
}

const SUBJECTS = [
  { id: 'classic', file: 'newton.jpg', name: '艾萨克·牛顿', nameEn: 'Isaac Newton', source: 'Portrait_of_Sir_Isaac_Newton,_1689_(head_shot_crop).jpg', credit: 'Godfrey Kneller, 1689; public domain (PD-Art, PD-old-100-expired)', crop: '1120x1400+480+30', gravity: 'northwest', black: 3, white: 1 },
  { id: 'em', file: 'maxwell2.jpg', name: '詹姆斯·克拉克·麦克斯韦', nameEn: 'James Clerk Maxwell', source: 'James_Clerk_Maxwell_big.jpg', credit: 'G. J. Stodart after Fergus of Greenock, published 1882; public domain (PD-old)', crop: '84%x96%+0+0', gravity: 'north', negate: true, black: 1, white: 1 },
  { id: 'relativity', file: 'einstein-nobel.png', name: '阿尔伯特·爱因斯坦', nameEn: 'Albert Einstein', source: 'Albert_Einstein_(Nobel).png', credit: 'Nobel Prize official portrait, circa 1921; public domain (PD-old-70, PD-US-expired)', crop: '94%x84%+0+0', gravity: 'north', black: 3, white: 1 },
  { id: 'quantum', file: 'bohr.jpg', name: '尼尔斯·玻尔', nameEn: 'Niels Bohr', source: 'Niels_Bohr.jpg', credit: 'AB Lagrelius & Westphal, circa 1922; public domain (PD-Sweden-photo, PD-US-expired)', crop: '86%x84%+0+0', gravity: 'north', black: 4, white: 1 },
  { id: 'math', file: 'euler.jpg', name: '莱昂哈德·欧拉', nameEn: 'Leonhard Euler', source: 'Leonhard_Euler.jpg', credit: 'Jakob Emanuel Handmann, 1753; public domain (PD-Art, PD-old-100-expired)', crop: '78%x82%+0+0', gravity: 'north', black: 2, white: 1 },
]
const WIDTH = 80
const HEIGHT = 100

function sample(subject) {
  const input = resolve(srcDir, subject.file)
  // Explicit raw 8-bit output avoids PGM headers and ImageMagick's 16-bit default.
  const pixels = execFileSync('magick', [
    input, '-gravity', subject.gravity, '-crop', subject.crop, '+repage',
    '-colorspace', 'Gray', ...(subject.negate ? ['-negate'] : []),
    '-contrast-stretch', `${subject.black}%x${subject.white}%`,
    '-resize', `${WIDTH}x${HEIGHT}^`, '-gravity', 'center',
    '-extent', `${WIDTH}x${HEIGHT}`, '-unsharp', '0x0.6+0.65+0.01',
    '-depth', '8', 'gray:-',
  ])
  if (pixels.length !== WIDTH * HEIGHT) throw new Error(`Invalid pixel count for ${subject.id}`)
  for (let y = 0; y < HEIGHT; y += 1) {
    for (let x = 0; x < WIDTH; x += 1) {
      // Feather only the outer frame; dark eyes and facial contours retain their tone.
      const edge = Math.min(x, WIDTH - 1 - x, y, HEIGHT - 1 - y)
      const fade = Math.min(1, edge / 5)
      pixels[y * WIDTH + x] = Math.round(pixels[y * WIDTH + x] * fade * fade * (3 - 2 * fade))
    }
  }
  writeFileSync(resolve(srcDir, `${subject.id}-grid.pgm`), Buffer.concat([Buffer.from(`P5\n${WIDTH} ${HEIGHT}\n255\n`), pixels]))
  return { hex: pixels.toString('hex'), sha256: createHash('sha256').update(readFileSync(input)).digest('hex') }
}

const out = [
  '/** Public-domain portrait luminance grids. Generated by bake-portraits.mjs; do not hand-edit. */',
  'export type PortraitPoints = Array<readonly [number, number, number]>',
  `export const PORTRAIT_GRID = { width: ${WIDTH}, height: ${HEIGHT}, step: 0.02 } as const`,
  '',
  'function decodeLuminance(hex: string): PortraitPoints {',
  '  return Array.from({ length: PORTRAIT_GRID.width * PORTRAIT_GRID.height }, (_, index) => [',
  '    ((index % PORTRAIT_GRID.width) + 0.5 - PORTRAIT_GRID.width / 2) * PORTRAIT_GRID.step,',
  '    (PORTRAIT_GRID.height / 2 - Math.floor(index / PORTRAIT_GRID.width) - 0.5) * PORTRAIT_GRID.step,',
  '    Number.parseInt(hex.slice(index * 2, index * 2 + 2), 16),',
  '  ] as const)',
  '}',
  '',
  'export const PORTRAITS: Record<string, { name: string; nameEn: string; source: string; credit: string; sourceSha256: string; points: PortraitPoints }> = {',
]
for (const subject of SUBJECTS) {
  const { hex, sha256 } = sample(subject)
  out.push(`  ${subject.id}: {`,
    `    name: ${JSON.stringify(subject.name)}, nameEn: ${JSON.stringify(subject.nameEn)},`,
    `    source: ${JSON.stringify(`https://commons.wikimedia.org/wiki/File:${subject.source}`)},`,
    `    credit: ${JSON.stringify(subject.credit)},`,
    `    sourceSha256: '${sha256}',`,
    `    points: decodeLuminance('${hex}'),`,
    '  },')
  console.log(subject.id, WIDTH * HEIGHT, 'points')
}
out.push('}\n')
writeFileSync(outPath, out.join('\n'))
console.log('wrote', outPath)
