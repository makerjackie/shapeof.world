import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { chromium } from 'playwright'
import { findStaticVariable, staticLiteralValue } from './lib/static-typescript-data.mjs'

// Only tiny grid cells use these rasters. Preview and live synthesis stay vector.
const root = resolve(import.meta.dirname, '..')
const world = resolve(root, 'src/components/experiences/worlds/periodic-table')
const assets = staticLiteralValue(findStaticVariable(resolve(world, 'synthesis-data.ts'), 'synthesisAssets'))
const assetRoot = '/assets/worlds/periodic-table/synthesis/thumb'
const directory = resolve(root, `public${assetRoot}`)
const path = (asset) => resolve(root, `public${asset}`)
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex')
const check = process.argv.includes('--check')
const transform = ['-strip', '-quality', '82', '-define', 'webp:method=6']
const tool = execFileSync('magick', ['-version'], { encoding: 'utf8' }).split('\n')[0]
const browser = await chromium.launch({ headless: true })
const renderer = `Chromium ${browser.version()}; full SVG rendered to transparent 160x120 canvas`
const page = await browser.newPage()
const records = [], map = {}
if (!check) mkdirSync(directory, { recursive: true })
try {
for (const [symbol, source] of Object.entries(assets)) {
  const original = readFileSync(path(source)), sourceSha256 = hash(original)
  // Match browser SVG gradients and groups exactly; ImageMagick's own SVG
  // renderer turns these nested nucleon gradients black on some builds.
  const png = await page.evaluate(async (svg) => {
    const image = new Image(); image.src = svg; await image.decode()
    const canvas = document.createElement('canvas'); canvas.width = 160; canvas.height = 120
    canvas.getContext('2d').drawImage(image, 0, 0, 160, 120)
    return canvas.toDataURL('image/png').split(',')[1]
  }, `data:image/svg+xml;base64,${original.toString('base64')}`)
  const bytes = execFileSync('magick', ['png:-', ...transform, 'webp:-'], { input: Buffer.from(png, 'base64') })
  const sha256 = hash(bytes), asset = `${assetRoot}/${symbol}-160-${sha256.slice(0, 12)}.webp`
  const [width, height] = execFileSync('magick', ['identify', '-format', '%w %h', '-'], { input: bytes, encoding: 'utf8' }).split(' ').map(Number)
  if (bytes.length > 20 * 1024 || width !== 160 || height !== 120) throw new Error(`Invalid diagram thumbnail: ${symbol}`)
  if (check) { if (!readFileSync(path(asset)).equals(bytes)) throw new Error(`Stale diagram thumbnail: ${symbol}`) }
  else writeFileSync(path(asset), bytes)
  map[symbol] = { src: asset, width, height }
  records.push({ symbol, asset, source, sourceSha256, sha256, bytes: bytes.length, width, height, transform,
    credit: 'Shape of the World', license: 'CC BY-NC 4.0', licenseUrl: 'https://creativecommons.org/licenses/by-nc/4.0/' })
}
} finally { await browser.close() }
const module = '// Generated by node scripts/generate-periodic-table-diagram-thumbnails.mjs. Do not edit.\n' +
  'import type { SpecimenImageVariant } from "./image-variants"\n' +
  `export const diagramThumbnails: Readonly<Record<string, SpecimenImageVariant>> = ${JSON.stringify(map, null, 2)}\n`
for (const [file, contents] of [[resolve(directory, 'sources.json'), JSON.stringify({ tool, renderer, records }, null, 2) + '\n'], [resolve(world, 'diagram-thumbnails.ts'), module]]) {
  if (check) { if (readFileSync(file, 'utf8') !== contents) throw new Error(`Stale generated file: ${file}`) }
  else writeFileSync(file, contents)
}
console.log(`${check ? 'Verified' : 'Generated'} ${records.length} diagram thumbnails, ${records.reduce((n, row) => n + row.bytes, 0)} bytes; SVG sources unchanged.`)
