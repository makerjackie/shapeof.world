import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import ts from 'typescript'
import { findStaticVariable, staticLiteralValue } from './lib/static-typescript-data.mjs'

// Run with Node 24+ and ImageMagick 7. Only generates derivatives; never edits sources.
const root = resolve(import.meta.dirname, '..')
const world = resolve(root, 'src/components/experiences/worlds/periodic-table')
const assetRoot = '/assets/worlds/periodic-table/responsive'
const directory = resolve(root, `public${assetRoot}`)
const check = process.argv.includes('--check')
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')
const readAsset = (asset) => readFileSync(resolve(root, `public${asset}`))
const displayImages = staticLiteralValue(findStaticVariable(resolve(world, 'display-images.ts'), 'displayImages'))
const cutouts = staticLiteralValue(findStaticVariable(resolve(world, 'cutout-images.ts'), 'specimenCutouts'))
const photoObject = findStaticVariable(resolve(world, 'photo-data.ts'), 'elementPhotos')
const photos = Object.fromEntries(photoObject.properties.flatMap((property) => {
  if (!ts.isPropertyAssignment(property)) throw new Error('Expected an explicit element photo entry')
  const symbol = property.name.text
  const value = property.initializer
  if (ts.isPropertyAccessExpression(value) && value.expression.getText() === 'synthesisImages') return []
  return [[symbol, staticLiteralValue(value)]]
}))
const variants = [
  { name: 'thumbnail', edge: 160, quality: 72, maxBytes: 20 * 1024 },
  { name: 'preview', edge: 640, quality: 78, maxBytes: 100 * 1024 },
]
const recipe = (variant) => [
  '-auto-orient', '-resize', `${variant.edge}x${variant.edge}>`, '-strip',
  '-quality', String(variant.quality), '-define', 'webp:method=6',
]
const toolVersion = () => execFileSync('magick', ['-version'], { encoding: 'utf8' }).split('\n')[0]
const dimensions = (buffer) => execFileSync('magick', ['identify', '-format', '%w %h', '-'], { input: buffer, encoding: 'utf8' }).trim().split(' ').map(Number)
const map = {}
const records = []
const bySource = new Map()
const existing = check ? JSON.parse(readFileSync(resolve(directory, 'sources.json'), 'utf8')) : null
if (check && existing.tool !== toolVersion()) throw new Error(`Use the recorded converter: ${existing.tool}`)
if (!check) mkdirSync(directory, { recursive: true })

for (const [symbol, photo] of Object.entries(photos)) {
  const source = cutouts[symbol] ?? displayImages[symbol] ?? photo.src
  if (!source.endsWith('.webp')) throw new Error(`Unsupported photographic input: ${source}`)
  if (!bySource.has(source)) {
    const sourceBytes = readAsset(source)
    const [sourceWidth, sourceHeight] = dimensions(sourceBytes)
    const result = {}
    for (const variant of variants) {
      const bytes = execFileSync('magick', [resolve(root, `public${source}`), ...recipe(variant), 'webp:-'], { maxBuffer: 8 * 1024 * 1024 })
      const hash = sha256(bytes)
      const [width, height] = dimensions(bytes)
      if (bytes.length > variant.maxBytes) throw new Error(`${symbol} ${variant.name}: ${bytes.length} bytes exceeds budget`)
      const asset = `${assetRoot}/${symbol}-${variant.edge}-${hash.slice(0, 12)}.webp`
      if (check) {
        if (!readAsset(asset).equals(bytes)) throw new Error(`Stale image: ${asset}`)
      } else writeFileSync(resolve(root, `public${asset}`), bytes)
      result[variant.name] = { src: asset, width, height }
      records.push({
        asset, sha256: hash, bytes: bytes.length, width, height, purpose: variant.name,
        source, sourceSha256: sha256(sourceBytes), sourceWidth, sourceHeight,
        referenceAsset: photo.src, referenceSha256: sha256(readAsset(photo.src)),
        sourceUrl: photo.sourceUrl, credit: photo.credit, license: photo.license, licenseUrl: photo.licenseUrl,
        transform: recipe(variant),
      })
    }
    bySource.set(source, result)
  }
  map[symbol] = bySource.get(source)
}

const manifest = `${JSON.stringify({ tool: existing?.tool ?? toolVersion(), records }, null, 2)}\n`
const module = `// Generated by node scripts/generate-periodic-table-images.mjs. Do not edit.\n` +
  `export interface SpecimenImageVariant { src: string; width: number; height: number }\n` +
  `export const specimenImageVariants: Readonly<Record<string, { thumbnail: SpecimenImageVariant; preview: SpecimenImageVariant }>> = ${JSON.stringify(map, null, 2)}\n`
for (const [file, contents] of [[resolve(directory, 'sources.json'), manifest], [resolve(world, 'image-variants.ts'), module]]) {
  if (check) {
    if (readFileSync(file, 'utf8') !== contents) throw new Error(`Stale generated file: ${file}`)
  } else writeFileSync(file, contents)
}
for (const variant of variants) {
  const rows = records.filter((row) => row.purpose === variant.name)
  console.log(`${variant.name}: ${rows.length} files, ${rows.reduce((sum, row) => sum + row.bytes, 0)} bytes, max ${Math.max(...rows.map((row) => row.bytes))} bytes`)
}
console.log(`${check ? 'Verified' : 'Generated'} variants for ${Object.keys(map).length} element positions; SVG diagrams stay vector.`)
